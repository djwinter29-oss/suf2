#!/usr/bin/env python3
"""Turn P-256 public keys into a C header for the SUF2 loader.

Each input is a PEM public key (SubjectPublicKeyInfo) or a PEM/DER X.509
certificate. Only the public key is used; certificates are not validated as
a chain. The loader trusts every key listed here equally.

    suf2_keys_header.py --output suf2_keys.h key1.pem cert2.pem

With --production the script refuses example or test material: anything under
a --forbid-dir, and any certificate whose subject says "TEST ONLY".
"""

import argparse
import hashlib
import sys
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec


def load_public_key(path: Path) -> tuple[ec.EllipticCurvePublicKey, str | None]:
    data = path.read_bytes()
    subject = None
    if b"BEGIN CERTIFICATE" in data:
        cert = x509.load_pem_x509_certificate(data)
        key, subject = cert.public_key(), cert.subject.rfc4514_string()
    elif b"BEGIN PUBLIC KEY" in data:
        key = serialization.load_pem_public_key(data)
    elif b"PRIVATE KEY" in data:
        raise ValueError("this is a private key; give the loader only the public key or certificate")
    else:
        cert = x509.load_der_x509_certificate(data)
        key, subject = cert.public_key(), cert.subject.rfc4514_string()
    if not isinstance(key, ec.EllipticCurvePublicKey) or key.curve.name != "secp256r1":
        raise ValueError("not a P-256 (secp256r1) public key")
    return key, subject


def is_under(path: Path, folder: Path) -> bool:
    try:
        path.resolve().relative_to(folder.resolve())
        return True
    except ValueError:
        return False


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("keys", nargs="+", type=Path, help="PEM public keys or X.509 certificates")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--production", action="store_true", help="reject example and test keys")
    parser.add_argument("--forbid-dir", type=Path, action="append", default=[],
                        help="folder of example material that --production refuses")
    args = parser.parse_args()

    entries, seen = [], set()
    for path in args.keys:
        try:
            key, subject = load_public_key(path)
        except (OSError, ValueError) as error:
            parser.error(f"{path}: {error}")
        if args.production:
            if any(is_under(path, folder) for folder in args.forbid_dir):
                parser.error(f"{path}: example/test key folder is not allowed in a production build")
            if subject and "TEST ONLY" in subject.upper():
                parser.error(f"{path}: certificate is marked TEST ONLY")
        point = key.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
        key_id = hashlib.sha256(point).digest()[:16].hex()
        if key_id in seen:
            parser.error(f"{path}: duplicate key {key_id}")
        seen.add(key_id)
        entries.append((path.name, key_id, point))

    lines = [
        "/* Generated by tools/firmware/suf2_keys_header.py. Do not edit. */",
        "#pragma once",
        "#include \"suf2/suf2.h\"",
        "",
        "static const suf2_signing_key_t suf2_trusted_keys[] = {",
    ]
    for name, key_id, point in entries:
        lines.append(f"    /* {name}, key ID {key_id} */")
        lines.append("    {{")
        for i in range(0, len(point), 13):
            lines.append("        " + " ".join(f"0x{b:02x}," for b in point[i:i + 13]))
        lines.append("    }},")
    lines += ["};", "", f"#define SUF2_TRUSTED_KEY_COUNT {len(entries)}u", ""]

    text = "\n".join(lines)
    if not args.output.exists() or args.output.read_text() != text:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
